const patterns = Object.entries(english).filter(([key])=>key.includes('{')).map(([key,value])=>({
 regex: new RegExp('^'+key.split(/(\{\d+\})/).map(part=>/^\{\d+\}$/.test(part)?'(.*?)':part.replace(/[.*+?^$()|[\]\\]/g,'\\$&')).join('')+'$'), value
}));
export function translate(text:string, language:Language):string {
 const normalized=text.replace(/\s+/g,' ').trim();
 const dictionary=language==='en'?english:indonesian;
 let result=dictionary[normalized];
 if(result===undefined && language==='en') for(const {regex,value} of patterns){const match=normalized.match(regex);if(match){result=value.replace(/\{(\d+)\}/g,(_,index)=>match[Number(index)+1]);break;}}
 if(result===undefined)return text;
 return (text.match(/^\s*/)?.[0]||'')+result+(text.match(/\s*$/)?.[0]||'');
}
